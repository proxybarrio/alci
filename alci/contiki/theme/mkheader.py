def bits(pat, f):
    out = []
    for y, r in enumerate(pat):
        v = 0
        for x, ch in enumerate(r):
            v = (v << 1) | int(f(ch, x, y))
        out.append(v)
    return out
def arr(name, b): return 'static const unsigned char %s[8] = {%s};' % (name, ','.join('0x%02x' % v for v in b))
