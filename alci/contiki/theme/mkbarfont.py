"""Write elks/font-bar.h: the small font for bars on 8-pixel cells.
Source: the X11 misc-fixed 5x7 font (public domain), emboldened by one pixel
sideways where no gap closes and placed from the second row of the cell, so no letter touches a
bar edge.  Needs the X11 font file (Debian package xfonts-base).
usage: python3 theme/mkbarfont.py > elks/font-bar.h"""
import gzip, io, sys
import numpy as np
from PIL import PcfFontFile, ImageFont, Image, ImageDraw
src = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/X11/misc/5x7.pcf.gz'
pf = PcfFontFile.PcfFontFile(gzip.open(src))
pf.save('/tmp/bar5x7')
fo = ImageFont.load('/tmp/bar5x7.pil')
print('/* Small bar font for 8-pixel cells, generated by theme/mkbarfont.py from the')
print('   X11 misc-fixed 5x7 font (public domain), emboldened; ASCII 32-127, 8 rows')
print('   per glyph, glyph in rows 1-7, leftmost pixel in the most significant bit. */')
print('static const unsigned char font_bar[96][8] = {')
for c in range(32, 128):
    im = Image.new('L', (8, 8), 0)
    if c < 127:
        ImageDraw.Draw(im).text((1, 1), chr(c), font=fo, fill=255)
    g = np.asarray(im) > 127
    # embolden: each pixel also fills the one to its right, unless the pixel
    # after that is set (that would close a one-pixel gap: M, N, W, 0, #)
    b = g.copy()
    for y in range(8):
        for x in range(7):
            if g[y, x] and not g[y, x + 1] and not (x + 2 < 8 and g[y, x + 2]):
                b[y, x + 1] = True
    g = b
    g[0] = False
    row = [int(''.join('1' if v else '0' for v in r), 2) for r in g]
    print('  {%s},' % ','.join('0x%02x' % v for v in row))
print('};')
