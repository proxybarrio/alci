"""Write elks/font-bar.h: the small font for bars on two-colour screens
(title bars, menu bar, status bar, buttons, icon titles), as on the trial
approved on 2026-11-23: the X11 Schumacher Clean 6x6 font (clR6x6),
emboldened by one pixel sideways, placed from the second row of the cell
so the bar lines stay clear of it. Needs the X11 font file (Debian package
xfonts-75dpi or xfonts-100dpi).
usage: python3 theme/mkbarfont.py > elks/font-bar.h"""
import gzip, sys
import numpy as np
from PIL import PcfFontFile, ImageFont, Image, ImageDraw
src = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/X11/misc/clR6x6.pcf.gz'
PcfFontFile.PcfFontFile(gzip.open(src)).save('/tmp/barclr6x6')
fo = ImageFont.load('/tmp/barclr6x6.pil')
print('/* Small bar font for two-colour screens, generated by theme/mkbarfont.py')
print('   from the X11 font clR6x6 (Schumacher Clean, Copyright 1989 Dale Schumacher,')
print('   free to use, copy, modify and distribute with this notice), emboldened;')
print('   ASCII 32-127, 8 rows per glyph, leftmost pixel in the top bit. */')
print('static const unsigned char font_bar[96][8] = {')
for c in range(32, 128):
    im = Image.new('L', (8, 8), 0)
    if c < 127:
        ImageDraw.Draw(im).text((1, 1), chr(c), font=fo, fill=255)
    g = np.asarray(im) > 127
    g = g | np.roll(g, 1, axis=1)
    row = [int(''.join('1' if v else '0' for v in r), 2) for r in g]
    print('  {%s},' % ','.join('0x%02x' % v for v in row))
print('};')
