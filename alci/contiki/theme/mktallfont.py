"""Write elks/font-tall<h>.h: the font of the two-colour screens with tall
cells (Hercules, 640x400, EGA and VGA in two colours), as on the trials of
2026-11-23: the X11 Schumacher Clean Bold fonts clB8x14 and clB8x16. Each
glyph has an empty row in front, so that the bars can take it one row
lower (from the first row) and the rest from the second. Needs the X11 font
files (Debian package xfonts-base).
usage: python3 theme/mktallfont.py 14 > elks/font-tall14.h"""
import gzip, sys
import numpy as np
from PIL import PcfFontFile, ImageFont, Image, ImageDraw
h = int(sys.argv[1])
src = sys.argv[2] if len(sys.argv) > 2 else '/usr/share/fonts/X11/misc/clB8x%d.pcf.gz' % h
PcfFontFile.PcfFontFile(gzip.open(src)).save('/tmp/tallclb8x%d' % h)
fo = ImageFont.load('/tmp/tallclb8x%d.pil' % h)
print('/* Font of the two-colour screens with %d-row cells, generated by' % h)
print('   theme/mktallfont.py from the X11 font clB8x%d (Schumacher Clean Bold,' % h)
print('   Copyright 1989 Dale Schumacher, free to use, copy, modify and distribute')
print('   with this notice); ASCII 32-127, an empty row then %d rows per glyph,' % h)
print('   leftmost pixel in the top bit. */')
print('static const unsigned char font_tall[96][%d] = {' % (h + 1))
for c in range(32, 128):
    im = Image.new('L', (8, h), 0)
    if c < 127:
        ImageDraw.Draw(im).text((0, 0), chr(c), font=fo, fill=255)
    g = np.asarray(im) > 127
    row = [0] + [int(''.join('1' if v else '0' for v in r), 2) for r in g]
    print('  {%s},' % ','.join('0x%02x' % v for v in row))
print('};')
