"""Pack the Alci icon PNGs into C headers and icon-set files.

Usage: python3 mkicons.py <png-directory> <out-directory>

For each screen family it writes:
  <set>.h    C arrays, to build a set into a program (the disk default);
  <set>.ais  one file with the whole set, for sets installed later by ept.

Layouts (see README.md):
  cell layout: the icon is cut into text cells (8x8 or 8x16 pixels), cells
               stored left to right, top to bottom; inside a cell one byte
               (1 bpp) or two bytes (2 bpp) per pixel row, leftmost pixel in
               the most significant bits. This is the order the CTK drawing
               layer writes to video memory.
  row layout:  plain rows, 4 bpp, two pixels per byte, left pixel in the
               high nibble, rows padded to a whole byte.

.ais file, little endian:
  "AIS1"  magic
  u8      bits per pixel
  u8      cell width  (0 = row layout)
  u8      cell height (0 = row layout)
  u8      number of palette entries
  u16     icon width in pixels
  u16     icon height in pixels
  u8      number of icons
  u8      index of the paper (background) colour
  palette entries, 3 bytes each (R, G, B, 0-255)
  per icon: 12-byte name (zero padded), then the bitmap
"""
import os
import struct
import sys
from PIL import Image

NAMES = ['about', 'calculator', 'dhcp', 'directory', 'editor', 'email', 'ftp', 'irc',
         'netconf', 'processes', 'shell', 'telnet', 'telnetd', 'vnc', 'www', 'webserver']

# set name: (bits per pixel, cell width, cell height, paper index)
SETS = {
    'cga640-mono':       (1, 8, 8, 0),
    'cga320-4col':       (2, 8, 8, 0),
    'hires640x400-mono': (1, 8, 16, 0),
    'vga640-16col':      (4, 0, 0, 1),
}


def pack_cells(px, w, h, bpp, cw, ch):
    per = 8 // bpp
    out = bytearray()
    for cy in range(0, h, ch):
        for cx in range(0, w, cw):
            for y in range(cy, cy + ch):
                for x0 in range(cx, cx + cw, per):
                    b = 0
                    for x in range(x0, x0 + per):
                        b = (b << bpp) | px[y * w + x]
                    out.append(b)
    return out


def pack_rows(px, w, h, bpp):
    per = 8 // bpp
    out = bytearray()
    for y in range(h):
        for x0 in range(0, w, per):
            b = 0
            for x in range(x0, x0 + per):
                b = (b << bpp) | (px[y * w + x] if x < w else 0)
            out.append(b)
    return out


def build(pngdir, outdir, name):
    bpp, cw, ch, paper = SETS[name]
    icons = []
    pal = None
    for n in NAMES:
        im = Image.open(os.path.join(pngdir, name, n + '.png'))
        if im.mode != 'P':
            sys.exit(f'{name}/{n}.png is not an indexed PNG')
        w, h = im.size
        px = list(im.tobytes())
        ncol = 1 << bpp
        if max(px) >= ncol:
            sys.exit(f'{name}/{n}.png uses more than {ncol} colours')
        p = im.getpalette()[:3 * ncol]
        if pal is None:
            pal, size = p, (w, h)
        elif p != pal or (w, h) != size:
            sys.exit(f'{name}/{n}.png: palette or size differs from the rest of the set')
        if cw and (w % cw or h % ch):
            sys.exit(f'{name}/{n}.png: {w}x{h} is not a whole number of {cw}x{ch} cells')
        data = pack_cells(px, w, h, bpp, cw, ch) if cw else pack_rows(px, w, h, bpp)
        icons.append((n, data))
    w, h = size
    ncol = 1 << bpp
    blob = bytearray(b'AIS1')
    blob += struct.pack('<BBBBHHBB', bpp, cw, ch, ncol, w, h, len(icons), paper)
    blob += bytes(pal)
    for n, data in icons:
        blob += n[:12].encode().ljust(12, b'\0') + data
    with open(os.path.join(outdir, name + '.ais'), 'wb') as f:
        f.write(blob)

    cname = name.replace('-', '_')
    up = cname.upper()
    lines = [f'/* {name}: generated by mkicons.py from png/{name}/, do not edit. */',
             f'#define ICONS_{up}_W      {w}   /* pixels */',
             f'#define ICONS_{up}_H      {h}',
             f'#define ICONS_{up}_BPP    {bpp}']
    if cw:
        lines += [f'#define ICONS_{up}_CELLSW {w // cw}   /* text cells */',
                  f'#define ICONS_{up}_CELLSH {h // ch}']
    lines += [f'#define ICONS_{up}_BYTES  {len(icons[0][1])}', '']
    if not cw:
        lines.append(f'static const unsigned char icons_{cname}_palette[{3 * ncol}] = {{ /* R,G,B 0-255 */')
        lines += ['  ' + ','.join(f'{v}' for v in pal[i:i + 12]) + ',' for i in range(0, len(pal), 12)]
        lines += ['};', '']
    for n, data in icons:
        lines.append(f'static const unsigned char icon_{cname}_{n}[{len(data)}] = {{')
        for i in range(0, len(data), 16):
            lines.append('  ' + ','.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
        lines.append('};')
    with open(os.path.join(outdir, name + '.h'), 'w') as f:
        f.write('\n'.join(lines) + '\n')
    return len(blob)


def main(pngdir, outdir):
    os.makedirs(outdir, exist_ok=True)
    for name in SETS:
        size = build(pngdir, outdir, name)
        print(f'{name}.ais  {size} bytes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
